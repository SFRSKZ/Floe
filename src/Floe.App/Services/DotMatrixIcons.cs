    private static readonly Dictionary<(string Key, double Size, Color Color, double Dpi), BitmapSource> Cache = new();
    private static readonly object CacheGate = new();

    /// <summary>
    /// Renders the icon identified by <paramref name="key"/> at the given size
    /// in DIP, or returns <c>null</c> when the key is unknown.
    /// </summary>
    public static BitmapSource? Render(string key, double sizeDip, Color color, double dpiScale = 1.0)
    {
        if (string.IsNullOrEmpty(key) || !Grids.TryGetValue(key, out var grid))
        {
            return null;
        }

        if (!(sizeDip > 0) || double.IsNaN(sizeDip))
        {
            return null;
        }

        if (!(dpiScale > 0) || double.IsNaN(dpiScale))
        {
            dpiScale = 1.0;
        }

        // Normalise before both caching and drawing so the cached bitmap always
        // matches the key it is stored under.
        sizeDip = Math.Round(sizeDip, 2);
        dpiScale = Math.Round(dpiScale, 3);

        var cacheKey = (key.ToLowerInvariant(), sizeDip, color, dpiScale);
        lock (CacheGate)
        {
            if (Cache.TryGetValue(cacheKey, out var cached))
            {
                return cached;
            }
        }

        var bitmap = Draw(grid, sizeDip, color, dpiScale);

        lock (CacheGate)
        {
            Cache[cacheKey] = bitmap;
        }

        return bitmap;
    }

    private static BitmapSource Draw(string[] grid, double sizeDip, Color color, double dpiScale)
    {
        int pixels = Math.Max(1, (int)Math.Round(sizeDip * dpiScale));
        double cell = (double)pixels / GridSize;
        double radius = cell * DotDiameterRatio / 2.0;
        double glowRadius = radius * GlowDiameterRatio;

        var dotBrush = new SolidColorBrush(color);
        dotBrush.Freeze();
        var glowBrush = new SolidColorBrush(Color.FromArgb(GlowAlpha, color.R, color.G, color.B));
        glowBrush.Freeze();

        var visual = new DrawingVisual();
        using (var dc = visual.RenderOpen())
        {
            // Glow pass first so the crisp dots stay on top of their halo.
            for (int y = 0; y < GridSize; y++)
            {
                string row = grid[y];
                for (int x = 0; x < GridSize && x < row.Length; x++)
                {
                    if (row[x] != '#')
                    {
                        continue;
                    }

                    var center = new Point((x + 0.5) * cell, (y + 0.5) * cell);
                    dc.DrawEllipse(glowBrush, null, center, glowRadius, glowRadius);
                }
            }

            for (int y = 0; y < GridSize; y++)
            {
                string row = grid[y];
                for (int x = 0; x < GridSize && x < row.Length; x++)
                {
                    if (row[x] != '#')
                    {
                        continue;
                    }

                    var center = new Point((x + 0.5) * cell, (y + 0.5) * cell);
                    dc.DrawEllipse(dotBrush, null, center, radius, radius);
                }
            }
        }

        var target = new RenderTargetBitmap(pixels, pixels, 96, 96, PixelFormats.Pbgra32);
        target.Render(visual);
        target.Freeze();
        return target;
    }
